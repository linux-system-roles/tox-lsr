# Set up a fake ansible.module_utils environment so that python module
# lookups for module_utils files work correctly.
#
# The role module_utils (DEST_MODULE_UTILS_DIR) and the test module_utils
# (TESTS_MODULE_UTILS_DIR, default: tests/module_utils next to the role
# module_utils) are linked into the ansible/module_utils directory of the
# tox environment (SRC_MODULE_UTILS_DIR).
#
# A package that exists in both the role and the tests module_utils is
# merged into a real directory containing links to the files of both, so
# that lookups like ansible.module_utils.<pkg>.<file> resolve no matter
# which of the two directories the file lives in.
#
# The cleanup refreshes the owned links individually, so that links to
# files that moved between the role and the tests module_utils do not
# linger. Python-generated bytecode (__pycache__ directories and .pyc
# files) is removed so that it cannot block the cleanup. Directories
# containing unrelated files are preserved.

set -euo pipefail

if [ -n "${DEBUG:-}" ] ; then
    set -x
fi

proceed=
case "$LSR_TOX_ENV_NAME" in
pylint) if [ -n "${RUN_PYLINT_SETUP_MODULE_UTILS:-}" ] ; then
            proceed=true
        fi ;;
py[23]*) if [ -n "${RUN_PYTEST_SETUP_MODULE_UTILS:-}" ] ; then
            proceed=true
        fi ;;
esac
if [ -z "$proceed" ] ; then
    exit 0
fi

if [ ! -d "${SRC_MODULE_UTILS_DIR:-}" ] ; then
    echo Either ansible is not installed, or there is no ansible/module_utils
    echo in "${SRC_MODULE_UTILS_DIR:-}" - Skipping
    exit 0
fi

if [ ! -d "${DEST_MODULE_UTILS_DIR:-}" ] ; then
    echo Role has no module_utils - Skipping
    exit 0
fi

# we need absolute path for $DEST_MODULE_UTILS_DIR
absmoddir=$( readlink -f "$DEST_MODULE_UTILS_DIR" )

# tests/module_utils holds module_utils files used only by the tests,
# e.g. modules in tests/library
testmoddir="${TESTS_MODULE_UTILS_DIR:-$(dirname "$absmoddir")/tests/module_utils}"
# canonical path of the tests module_utils, used to match links for the
# cleanup even if the directory no longer exists
abstestsmoddir=$( readlink -m "$testmoddir" )
# links are only created from the tests module_utils if it exists
if [ -d "$testmoddir" ] ; then
    havetestsmoddir=true
else
    havetestsmoddir=false
fi

# link the files of package directory $1 into directory $2
link_module_utils_files() {
    local item bnitem
    for item in "$1"/* ; do
        [ -e "$item" ] || [ -L "$item" ] || continue
        case "$item" in
            *__pycache__) continue;;
            *.pyc) continue;;
        esac
        bnitem=$( basename "$item" )
        if [ -e "$2/$bnitem" ] || [ -L "$2/$bnitem" ] ; then
            continue
        fi
        ln -s "$item" "$2/$bnitem"
    done
}

# remove $1 if it is a link into the role or the tests module_utils
remove_owned_link() {
    local lnitem
    if lnitem=$( readlink "$1" ) && test -n "$lnitem" ; then
        case "$lnitem" in
            *"${DEST_MODULE_UTILS_DIR}"*|*"$absmoddir"*) rm -f "$1" ;;
            *"$abstestsmoddir"*) rm -f "$1" ;;
        esac
    fi
}

# clean up old links to module_utils and refresh merged package
# directories created by earlier runs
for item in "$SRC_MODULE_UTILS_DIR"/* ; do
    [ -e "$item" ] || [ -L "$item" ] || continue
    if [ -L "$item" ] ; then
        # top level link
        remove_owned_link "$item"
        continue
    fi
    [ -d "$item" ] || continue
    # real directory, usually a merged package directory from an earlier
    # run: refresh the owned links individually and remove the
    # python-generated bytecode so that links to files that moved between
    # the role and the tests module_utils do not linger; keep unrelated
    # files and links
    for subitem in "$item"/* ; do
        [ -e "$subitem" ] || [ -L "$subitem" ] || continue
        case "$subitem" in
            */__pycache__) rm -rf "$subitem" ; continue ;;
            *.pyc) rm -f "$subitem" ; continue ;;
        esac
        if [ -L "$subitem" ] ; then
            remove_owned_link "$subitem"
        fi
    done
    # remove the directory itself if it is now empty; rmdir only removes
    # empty directories, so directories containing unrelated files are
    # preserved
    rmdir "$item" 2> /dev/null || true
done

# add new links to module_utils
for item in "$absmoddir"/* ; do
    [ -e "$item" ] || [ -L "$item" ] || continue
    case "$item" in
        *__pycache__) continue;;
        *.pyc) continue;;
        *__init__.py) continue;;
    esac
    bnitem=$( basename "$item" )
    destitem="$SRC_MODULE_UTILS_DIR/$bnitem"
    if [ "$havetestsmoddir" = true ] && [ -d "$item" ] &&
            [ -d "$abstestsmoddir/$bnitem" ] ; then
        # the package exists in both the role and the tests module_utils -
        # merge the files of both into a real directory of links
        mkdir -p "$destitem"
        link_module_utils_files "$item" "$destitem"
        link_module_utils_files "$abstestsmoddir/$bnitem" "$destitem"
    elif [ -d "$destitem" ] && [ ! -L "$destitem" ] ; then
        # destitem is a real directory, e.g. a merged package directory
        # from an earlier run that contains unrelated files - link the
        # files individually so that the directory is preserved
        link_module_utils_files "$item" "$destitem"
    else
        ln -s "$item" "$destitem"
    fi
done

# add new links for the items that exist only in the tests module_utils
if [ "$havetestsmoddir" = true ] ; then
    for item in "$abstestsmoddir"/* ; do
        [ -e "$item" ] || [ -L "$item" ] || continue
        case "$item" in
            *__pycache__) continue;;
            *.pyc) continue;;
            *__init__.py) continue;;
        esac
        bnitem=$( basename "$item" )
        destitem="$SRC_MODULE_UTILS_DIR/$bnitem"
        if [ -e "$destitem" ] || [ -L "$destitem" ] ; then
            continue
        fi
        ln -s "$item" "$destitem"
    done
fi
